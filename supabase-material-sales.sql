-- Add standalone inventory sales without rewriting existing CRM records.
-- Run after supabase-setup.sql has created the existing CRM tables.
BEGIN;

CREATE TABLE IF NOT EXISTS public.inventory_sales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  material_id BIGINT NOT NULL REFERENCES public.materials(id) ON DELETE RESTRICT,
  client_id BIGINT REFERENCES public.clients(id) ON DELETE SET NULL,
  material_name VARCHAR(255) NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_cost NUMERIC NOT NULL CHECK (unit_cost >= 0),
  unit_sale_price NUMERIC NOT NULL CHECK (unit_sale_price >= 0),
  total_cost NUMERIC NOT NULL CHECK (total_cost >= 0),
  sale_total NUMERIC NOT NULL CHECK (sale_total >= 0),
  profit NUMERIC NOT NULL,
  CHECK (total_cost = unit_cost * quantity),
  CHECK (sale_total = unit_sale_price * quantity),
  CHECK (profit = sale_total - total_cost),
  notes TEXT,
  date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.inventory_sale_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventory_sale_id BIGINT NOT NULL
    REFERENCES public.inventory_sales(id) ON DELETE CASCADE,
  amount NUMERIC NOT NULL CHECK (amount > 0),
  payment_type VARCHAR(20) NOT NULL DEFAULT 'cash'
    CHECK (payment_type IN ('cash', 'card', 'transfer')),
  notes TEXT,
  date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_inventory_sales_date
  ON public.inventory_sales(date);
CREATE INDEX IF NOT EXISTS idx_inventory_sales_client_id
  ON public.inventory_sales(client_id);
CREATE INDEX IF NOT EXISTS idx_inventory_sales_material_id
  ON public.inventory_sales(material_id);
CREATE INDEX IF NOT EXISTS idx_inventory_sale_payments_sale_id
  ON public.inventory_sale_payments(inventory_sale_id);
CREATE INDEX IF NOT EXISTS idx_inventory_sale_payments_date
  ON public.inventory_sale_payments(date);

GRANT USAGE ON SCHEMA public TO anon, authenticated;
ALTER TABLE public.inventory_sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventory_sale_payments ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS inventory_sales_crm_access ON public.inventory_sales;
CREATE POLICY inventory_sales_crm_access ON public.inventory_sales
  FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS inventory_sale_payments_crm_access
  ON public.inventory_sale_payments;
CREATE POLICY inventory_sale_payments_crm_access
  ON public.inventory_sale_payments FOR SELECT TO anon, authenticated USING (true);
REVOKE ALL ON public.inventory_sales, public.inventory_sale_payments
  FROM anon, authenticated;
GRANT SELECT ON public.inventory_sales, public.inventory_sale_payments
  TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.validate_inventory_sale_payment()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  sale_total_value NUMERIC;
  already_paid NUMERIC;
BEGIN
  SELECT sale_total
  INTO sale_total_value
  FROM public.inventory_sales
  WHERE id = NEW.inventory_sale_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Material savdosi topilmadi';
  END IF;

  SELECT COALESCE(SUM(amount), 0)
  INTO already_paid
  FROM public.inventory_sale_payments
  WHERE inventory_sale_id = NEW.inventory_sale_id
    AND id IS DISTINCT FROM NEW.id;

  IF NEW.amount <= 0 OR already_paid + NEW.amount > sale_total_value THEN
    RAISE EXCEPTION 'To‘lov material savdosining qolgan summasidan oshib ketadi';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS validate_inventory_sale_payment_trigger
  ON public.inventory_sale_payments;
CREATE TRIGGER validate_inventory_sale_payment_trigger
  BEFORE INSERT OR UPDATE OF inventory_sale_id, amount
  ON public.inventory_sale_payments
  FOR EACH ROW EXECUTE FUNCTION public.validate_inventory_sale_payment();

CREATE OR REPLACE FUNCTION public.create_inventory_sale(sale_data JSONB)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  material_row RECORD;
  sale_id_value BIGINT;
  material_id_value BIGINT;
  client_id_value BIGINT;
  quantity_value INTEGER;
  quantity_numeric NUMERIC;
  amount_paid_value NUMERIC;
  sale_total_value NUMERIC;
  total_cost_value NUMERIC;
BEGIN
  material_id_value := NULLIF(sale_data->>'material_id', '')::BIGINT;
  client_id_value := NULLIF(sale_data->>'client_id', '')::BIGINT;
  quantity_numeric := COALESCE(NULLIF(sale_data->>'quantity', '')::NUMERIC, 0);
  amount_paid_value := COALESCE(NULLIF(sale_data->>'amount_paid', '')::NUMERIC, 0);

  IF material_id_value IS NULL THEN
    RAISE EXCEPTION 'Materialni tanlang';
  END IF;
  IF quantity_numeric <= 0 OR quantity_numeric <> trunc(quantity_numeric) THEN
    RAISE EXCEPTION 'Sotiladigan miqdor musbat butun son bo‘lishi kerak';
  END IF;
  IF amount_paid_value < 0 THEN
    RAISE EXCEPTION 'Qabul qilingan summa manfiy bo‘lishi mumkin emas';
  END IF;
  IF COALESCE(NULLIF(sale_data->>'payment_type', ''), 'cash')
    NOT IN ('cash', 'card', 'transfer') THEN
    RAISE EXCEPTION 'To‘lov turini to‘g‘ri tanlang';
  END IF;

  SELECT id, name, stock_count, cost_price, sell_price
  INTO material_row
  FROM public.materials
  WHERE id = material_id_value
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Material omborda topilmadi';
  END IF;

  quantity_value := quantity_numeric::INTEGER;
  IF material_row.stock_count < quantity_value THEN
    RAISE EXCEPTION '% materialidan omborda faqat % dona bor',
      material_row.name, material_row.stock_count;
  END IF;

  IF client_id_value IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.clients WHERE id = client_id_value
  ) THEN
    RAISE EXCEPTION 'Tanlangan mijoz topilmadi';
  END IF;

  sale_total_value := material_row.sell_price * quantity_value;
  total_cost_value := material_row.cost_price * quantity_value;
  IF amount_paid_value > sale_total_value THEN
    RAISE EXCEPTION 'Qabul qilingan summa savdo jami summasidan oshmasligi kerak';
  END IF;

  INSERT INTO public.inventory_sales (
    material_id, client_id, material_name, quantity, unit_cost,
    unit_sale_price, total_cost, sale_total, profit, notes
  ) VALUES (
    material_row.id,
    client_id_value,
    material_row.name,
    quantity_value,
    material_row.cost_price,
    material_row.sell_price,
    total_cost_value,
    sale_total_value,
    sale_total_value - total_cost_value,
    NULLIF(btrim(sale_data->>'notes'), '')
  ) RETURNING id INTO sale_id_value;

  UPDATE public.materials
  SET stock_count = stock_count - quantity_value
  WHERE id = material_row.id;

  IF amount_paid_value > 0 THEN
    INSERT INTO public.inventory_sale_payments (
      inventory_sale_id, amount, payment_type, notes
    ) VALUES (
      sale_id_value,
      amount_paid_value,
      COALESCE(NULLIF(sale_data->>'payment_type', ''), 'cash'),
      'Material savdosi uchun to‘lov'
    );
  END IF;

  RETURN sale_id_value;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_inventory_sale_payment(
  sale_id BIGINT,
  amount NUMERIC,
  payment_type TEXT DEFAULT 'cash',
  notes TEXT DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  payment_id_value BIGINT;
  normalized_type TEXT := COALESCE(NULLIF(payment_type, ''), 'cash');
BEGIN
  IF amount IS NULL OR amount <= 0 THEN
    RAISE EXCEPTION 'To‘lov summasi noldan katta bo‘lishi kerak';
  END IF;
  IF normalized_type NOT IN ('cash', 'card', 'transfer') THEN
    RAISE EXCEPTION 'To‘lov turini to‘g‘ri tanlang';
  END IF;

  INSERT INTO public.inventory_sale_payments (
    inventory_sale_id, amount, payment_type, notes
  ) VALUES (
    sale_id, amount, normalized_type, NULLIF(btrim(notes), '')
  ) RETURNING id INTO payment_id_value;

  RETURN payment_id_value;
END;
$$;

REVOKE ALL ON FUNCTION public.create_inventory_sale(JSONB) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_inventory_sale(JSONB)
  TO anon, authenticated;
REVOKE ALL ON FUNCTION public.record_inventory_sale_payment(BIGINT, NUMERIC, TEXT, TEXT)
  FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.record_inventory_sale_payment(BIGINT, NUMERIC, TEXT, TEXT)
  TO anon, authenticated;

NOTIFY pgrst, 'reload schema';
COMMIT;
