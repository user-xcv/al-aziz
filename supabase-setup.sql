CREATE OR REPLACE FUNCTION validate_payment_order()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  order_client_id BIGINT;
  order_total NUMERIC;
  opening_paid NUMERIC;
  already_paid NUMERIC;
BEGIN
  IF NEW.expense_id IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT e.client_id, e.order_total, e.opening_paid
  INTO order_client_id, order_total, opening_paid
  FROM expenses AS e
  WHERE e.id = NEW.expense_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Bog‘langan buyurtma topilmadi';
  END IF;
  IF order_client_id <> NEW.client_id THEN
    RAISE EXCEPTION 'To‘lov mijozini buyurtma mijoziga moslang';
  END IF;

  SELECT COALESCE(SUM(amount), 0)
  INTO already_paid
  FROM payments
  WHERE expense_id = NEW.expense_id
    AND id IS DISTINCT FROM NEW.id;

  IF opening_paid + already_paid + NEW.amount > order_total THEN
    RAISE EXCEPTION 'To‘lov buyurtmaning qolgan summasidan oshib ketadi';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION sync_order_payments_total()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  affected_order_id BIGINT;
BEGIN
  IF TG_OP = 'DELETE' OR (TG_OP = 'UPDATE' AND OLD.expense_id IS DISTINCT FROM NEW.expense_id) THEN
    affected_order_id := OLD.expense_id;
    IF affected_order_id IS NOT NULL THEN
      UPDATE expenses
      SET overallmoney = opening_paid + COALESCE(
        (SELECT SUM(amount) FROM payments WHERE expense_id = affected_order_id), 0
      )
      WHERE id = affected_order_id;
    END IF;
  END IF;

  IF TG_OP <> 'DELETE' AND NEW.expense_id IS NOT NULL THEN
    UPDATE expenses
    SET overallmoney = opening_paid + COALESCE(
      (SELECT SUM(amount) FROM payments WHERE expense_id = NEW.expense_id), 0
    )
    WHERE id = NEW.expense_id;
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS validate_payment_order_trigger ON payments;
CREATE TRIGGER validate_payment_order_trigger
  BEFORE INSERT OR UPDATE OF expense_id, client_id, amount ON payments
  FOR EACH ROW EXECUTE FUNCTION validate_payment_order();

DROP TRIGGER IF EXISTS sync_order_payments_total_trigger ON payments;
CREATE TRIGGER sync_order_payments_total_trigger
  AFTER INSERT OR UPDATE OR DELETE ON payments
  FOR EACH ROW EXECUTE FUNCTION sync_order_payments_total();

CREATE OR REPLACE FUNCTION validate_inventory_sale_payment()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  sale_total_value NUMERIC;
  already_paid NUMERIC;
BEGIN
  SELECT sale_total
  INTO sale_total_value
  FROM public.inventory_sales
  WHERE id = NEW.inventory_sale_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Material savdosi topilmadi';
  END IF;

  SELECT COALESCE(SUM(amount), 0)
  INTO already_paid
  FROM public.inventory_sale_payments
  WHERE inventory_sale_id = NEW.inventory_sale_id
    AND id IS DISTINCT FROM NEW.id;

  IF NEW.amount <= 0 OR already_paid + NEW.amount > sale_total_value THEN
    RAISE EXCEPTION 'To‘lov material savdosining qolgan summasidan oshib ketadi';
  END IF;
  RETURN NEW;
END;
$$;

