    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON public.%I',
      'Allow all access to ' || table_name,
      table_name
    );
    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON public.%I',
      table_name || '_authenticated_access',
      table_name
    );
    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON public.%I',
      table_name || '_crm_access',
      table_name
    );
    IF table_name IN ('inventory_sales', 'inventory_sale_payments') THEN
      EXECUTE format(
        'CREATE POLICY %I ON public.%I FOR SELECT TO anon, authenticated USING (true)',
        table_name || '_crm_access',
        table_name
      );
      EXECUTE format('GRANT SELECT ON public.%I TO anon, authenticated', table_name);
    ELSE
      EXECUTE format(
        'CREATE POLICY %I ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true)',
        table_name || '_crm_access',
        table_name
      );
      EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO anon, authenticated', table_name);
      IF pg_get_serial_sequence(format('public.%I', table_name), 'id') IS NOT NULL THEN
        EXECUTE format(
          'GRANT USAGE, SELECT ON SEQUENCE %s TO anon, authenticated',
          pg_get_serial_sequence(format('public.%I', table_name), 'id')
        );
      END IF;
    END IF;
  END LOOP;
END $$;

