  COALESCE((SELECT SUM(COALESCE(NULLIF(totalprice, 0), price * count))
            FROM order_materials WHERE expense_id = expenses.id), 0) +
  COALESCE(bazis, 0) + COALESCE(cutting, 0) + COALESCE(kromka, 0) +
  COALESCE(piercing, 0) + COALESCE(rover, 0)
