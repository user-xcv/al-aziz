-- 1. CATEGORIES jadvali
CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. FORMATS jadvali
CREATE TABLE IF NOT EXISTS formats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  name VARCHAR(255) NOT NULL,
  default_price NUMERIC DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. MATERIALS jadvali
CREATE TABLE IF NOT EXISTS materials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  format_id BIGINT REFERENCES formats(id) ON DELETE SET NULL,
  name VARCHAR(255) NOT NULL,
  stock_count INTEGER DEFAULT 0,
  cost_price NUMERIC DEFAULT 0,
  sell_price NUMERIC DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. CLIENTS jadvali
CREATE TABLE IF NOT EXISTS clients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  phone_number VARCHAR(20),
  address TEXT,
  notes TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. EXPENSES jadvali (buyurtmalar)
CREATE TABLE IF NOT EXISTS expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  bazis NUMERIC DEFAULT 0,
  cutting NUMERIC DEFAULT 0,
  kromka NUMERIC DEFAULT 0,
  piercing NUMERIC DEFAULT 0,
  rover NUMERIC DEFAULT 0,
  masterfee NUMERIC DEFAULT 0,
  spares NUMERIC DEFAULT 0,
  anotherexpenses NUMERIC DEFAULT 0,
  overallmoney NUMERIC DEFAULT 0,
  payoff NUMERIC DEFAULT 0,
  date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. ORDER_MATERIALS jadvali (buyurtma materiallari)
CREATE TABLE IF NOT EXISTS order_materials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expense_id BIGINT NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
  material_name VARCHAR(255) NOT NULL,
  count INTEGER NOT NULL DEFAULT 0,
  price NUMERIC DEFAULT 0,
  totalPrice NUMERIC DEFAULT 0,
  format_id BIGINT,
  format_name VARCHAR(255),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 7. PAYMENTS jadvali (to'lovlar)
CREATE TABLE IF NOT EXISTS payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  amount NUMERIC NOT NULL DEFAULT 0,
  payment_type VARCHAR(20) DEFAULT 'cash' CHECK (payment_type IN ('cash', 'card', 'transfer')),
  notes TEXT,
  date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ============================================
-- INDEXLARNI QO'SHISH
-- ============================================

CREATE INDEX IF NOT EXISTS idx_formats_category_id ON formats(category_id);
CREATE INDEX IF NOT EXISTS idx_materials_category_id ON materials(category_id);
CREATE INDEX IF NOT EXISTS idx_materials_format_id ON materials(format_id);
CREATE INDEX IF NOT EXISTS idx_expenses_client_id ON expenses(client_id);
CREATE INDEX IF NOT EXISTS idx_expenses_date ON expenses(date);
CREATE INDEX IF NOT EXISTS idx_order_materials_expense_id ON order_materials(expense_id);
CREATE INDEX IF NOT EXISTS idx_payments_client_id ON payments(client_id);
CREATE INDEX IF NOT EXISTS idx_payments_date ON payments(date);
CREATE INDEX IF NOT EXISTS idx_clients_name ON clients(name);

