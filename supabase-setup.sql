BEGIN;

-- 1. CATEGORIES jadvali
CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. FORMATS jadvali
CREATE TABLE IF NOT EXISTS formats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  name VARCHAR(255) NOT NULL,
  default_price NUMERIC DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. MATERIALS jadvali
CREATE TABLE IF NOT EXISTS materials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  format_id BIGINT REFERENCES formats(id) ON DELETE SET NULL,
  name VARCHAR(255) NOT NULL,
  stock_count INTEGER NOT NULL DEFAULT 0 CHECK (stock_count >= 0),
  cost_price NUMERIC NOT NULL DEFAULT 0 CHECK (cost_price >= 0),
  markup_price NUMERIC NOT NULL DEFAULT 0,
  sell_price NUMERIC NOT NULL DEFAULT 0 CHECK (sell_price >= 0),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. CLIENTS jadvali
CREATE TABLE IF NOT EXISTS clients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  phone_number VARCHAR(20),
  address TEXT,
  notes TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. EXPENSES jadvali (buyurtmalar)
CREATE TABLE IF NOT EXISTS expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
  bazis NUMERIC DEFAULT 0,
  cutting NUMERIC DEFAULT 0,
  kromka NUMERIC DEFAULT 0,
  piercing NUMERIC DEFAULT 0,
  rover NUMERIC DEFAULT 0,
  masterfee NUMERIC DEFAULT 0,
  spares NUMERIC DEFAULT 0,
  anotherexpenses NUMERIC DEFAULT 0,
  overallmoney NUMERIC NOT NULL DEFAULT 0 CHECK (overallmoney >= 0),
  order_total NUMERIC NOT NULL DEFAULT 0 CHECK (order_total >= 0),
  opening_paid NUMERIC NOT NULL DEFAULT 0 CHECK (opening_paid >= 0),
  payoff NUMERIC DEFAULT 0,
  date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. ORDER_MATERIALS jadvali (buyurtma materiallari)
CREATE TABLE IF NOT EXISTS order_materials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expense_id BIGINT NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
  material_id BIGINT REFERENCES materials(id) ON DELETE SET NULL,
  material_name VARCHAR(255) NOT NULL,
  count INTEGER NOT NULL DEFAULT 0 CHECK (count > 0),
  price NUMERIC NOT NULL DEFAULT 0 CHECK (price >= 0),
  totalprice NUMERIC NOT NULL DEFAULT 0,
  unit_cost NUMERIC NOT NULL DEFAULT 0,
  total_cost NUMERIC NOT NULL DEFAULT 0,
  unit_markup NUMERIC NOT NULL DEFAULT 0,
  total_markup NUMERIC NOT NULL DEFAULT 0,
  format_id BIGINT,
  format_name VARCHAR(255),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 7. PAYMENTS jadvali (to'lovlar)
CREATE TABLE IF NOT EXISTS payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
  expense_id BIGINT REFERENCES expenses(id) ON DELETE SET NULL,
  amount NUMERIC NOT NULL DEFAULT 0 CHECK (amount > 0),
  payment_type VARCHAR(20) DEFAULT 'cash' CHECK (payment_type IN ('cash', 'card', 'transfer')),
  notes TEXT,
  date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Direct material sales are immutable inventory snapshots, separate from orders.
CREATE TABLE IF NOT EXISTS inventory_sales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  material_id BIGINT NOT NULL REFERENCES materials(id) ON DELETE RESTRICT,
  client_id BIGINT REFERENCES clients(id) ON DELETE SET NULL,
  material_name VARCHAR(255) NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_cost NUMERIC NOT NULL CHECK (unit_cost >= 0),
  unit_sale_price NUMERIC NOT NULL CHECK (unit_sale_price >= 0),
  total_cost NUMERIC NOT NULL CHECK (total_cost >= 0),
  sale_total NUMERIC NOT NULL CHECK (sale_total >= 0),
  profit NUMERIC NOT NULL,
  CHECK (total_cost = unit_cost * quantity),
  CHECK (sale_total = unit_sale_price * quantity),
  CHECK (profit = sale_total - total_cost),
  notes TEXT,
  date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS inventory_sale_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventory_sale_id BIGINT NOT NULL REFERENCES inventory_sales(id) ON DELETE CASCADE,
  amount NUMERIC NOT NULL CHECK (amount > 0),
  payment_type VARCHAR(20) NOT NULL DEFAULT 'cash'
    CHECK (payment_type IN ('cash', 'card', 'transfer')),
  notes TEXT,
  date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

