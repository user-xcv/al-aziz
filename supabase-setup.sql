CREATE OR REPLACE FUNCTION create_order_with_materials(order_data JSONB)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
  client_id_value BIGINT;
  new_order_id BIGINT;
  line JSONB;
  material_row RECORD;
  line_count INTEGER;
  line_count_value NUMERIC;
  unit_price NUMERIC;
  unit_markup NUMERIC;
  service_revenue NUMERIC;
  operating_costs NUMERIC;
  material_costs NUMERIC := 0;
  material_revenue NUMERIC := 0;
  order_total_value NUMERIC;
  initial_payment NUMERIC;
BEGIN
  initial_payment := COALESCE(NULLIF(order_data->>'overallmoney', '')::NUMERIC, 0);
  service_revenue :=
    COALESCE(NULLIF(order_data->>'bazis', '')::NUMERIC, 0) +
    COALESCE(NULLIF(order_data->>'cutting', '')::NUMERIC, 0) +
    COALESCE(NULLIF(order_data->>'kromka', '')::NUMERIC, 0) +
    COALESCE(NULLIF(order_data->>'piercing', '')::NUMERIC, 0) +
    COALESCE(NULLIF(order_data->>'rover', '')::NUMERIC, 0);
  operating_costs :=
    COALESCE(NULLIF(order_data->>'masterfee', '')::NUMERIC, 0) +
    COALESCE(NULLIF(order_data->>'spares', '')::NUMERIC, 0) +
    COALESCE(NULLIF(order_data->>'anotherexpenses', '')::NUMERIC, 0);

  IF initial_payment < 0 OR service_revenue < 0 THEN
    RAISE EXCEPTION 'Buyurtma summasi va xizmat haqlari manfiy bo‘lishi mumkin emas';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM jsonb_each_text(order_data) AS field
    WHERE field.key IN (
      'bazis', 'cutting', 'kromka', 'piercing', 'rover',
      'masterfee', 'spares', 'anotherexpenses'
    )
      AND NULLIF(field.value, '')::NUMERIC < 0
  ) THEN
    RAISE EXCEPTION 'Xizmat haqlari manfiy bo‘lishi mumkin emas';
  END IF;

  client_id_value := NULLIF(order_data->>'client_id', '')::BIGINT;
  IF client_id_value IS NULL THEN
    IF NULLIF(btrim(order_data->>'name'), '') IS NULL THEN
      RAISE EXCEPTION 'Mijozni tanlang yoki uning ismini kiriting';
    END IF;
    INSERT INTO clients (name, phone_number)
    VALUES (btrim(order_data->>'name'), NULLIF(btrim(order_data->>'phone_number'), ''))
    RETURNING id INTO client_id_value;
  END IF;

  FOR line IN
    SELECT value FROM jsonb_array_elements(COALESCE(order_data->'materials', '[]'::JSONB))
    ORDER BY (value->>'material_id')::BIGINT
  LOOP
    line_count_value := COALESCE(NULLIF(line->>'count', '')::NUMERIC, 0);
    IF line_count_value <= 0 OR line_count_value <> trunc(line_count_value) THEN
      RAISE EXCEPTION 'Material miqdori to‘g‘ri kiritilishi kerak';
    END IF;
    line_count := line_count_value::INTEGER;

    SELECT id, stock_count, cost_price, name
    INTO material_row
    FROM materials
    WHERE id = NULLIF(line->>'material_id', '')::BIGINT
    FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Tanlangan material omborda topilmadi';
    END IF;
    IF material_row.stock_count < line_count THEN
      RAISE EXCEPTION '% materialidan omborda faqat % dona bor', material_row.name, material_row.stock_count;
    END IF;

    unit_markup := CASE
      WHEN line ? 'unit_markup' THEN COALESCE(NULLIF(line->>'unit_markup', '')::NUMERIC, 0)
      ELSE COALESCE(NULLIF(line->>'price', '')::NUMERIC, material_row.cost_price) - material_row.cost_price
    END;
    unit_price := material_row.cost_price + unit_markup;
    IF unit_price < 0 THEN
      RAISE EXCEPTION 'Material sotish narxi manfiy bo‘lishi mumkin emas';
    END IF;

    UPDATE materials
    SET stock_count = stock_count - line_count
    WHERE id = material_row.id;
    material_costs := material_costs + material_row.cost_price * line_count;
    material_revenue := material_revenue + unit_price * line_count;
  END LOOP;
  order_total_value := service_revenue + material_revenue;
  IF initial_payment > order_total_value THEN
    RAISE EXCEPTION 'Avans buyurtma summasidan oshib ketmasligi kerak';
  END IF;

  INSERT INTO expenses (
    client_id, bazis, cutting, kromka, piercing, rover, masterfee,
    spares, anotherexpenses, overallmoney, order_total, opening_paid, payoff
  ) VALUES (
    client_id_value,
    COALESCE(NULLIF(order_data->>'bazis', '')::NUMERIC, 0),
    COALESCE(NULLIF(order_data->>'cutting', '')::NUMERIC, 0),
    COALESCE(NULLIF(order_data->>'kromka', '')::NUMERIC, 0),
    COALESCE(NULLIF(order_data->>'piercing', '')::NUMERIC, 0),
    COALESCE(NULLIF(order_data->>'rover', '')::NUMERIC, 0),
    COALESCE(NULLIF(order_data->>'masterfee', '')::NUMERIC, 0),
    COALESCE(NULLIF(order_data->>'spares', '')::NUMERIC, 0),
    COALESCE(NULLIF(order_data->>'anotherexpenses', '')::NUMERIC, 0),
    0,
    order_total_value,
    0,
    order_total_value - material_costs - operating_costs
  ) RETURNING id INTO new_order_id;

  IF initial_payment > 0 THEN
    INSERT INTO payments (client_id, expense_id, amount, payment_type, notes)
    VALUES (client_id_value, new_order_id, initial_payment, 'cash', 'Buyurtma ochilgandagi avans');
  END IF;

  FOR line IN SELECT value FROM jsonb_array_elements(COALESCE(order_data->'materials', '[]'::JSONB))
  LOOP
    SELECT cost_price INTO material_row
    FROM materials
    WHERE id = NULLIF(line->>'material_id', '')::BIGINT;
    line_count := (line->>'count')::INTEGER;
    unit_markup := CASE
      WHEN line ? 'unit_markup' THEN COALESCE(NULLIF(line->>'unit_markup', '')::NUMERIC, 0)
      ELSE COALESCE(NULLIF(line->>'price', '')::NUMERIC, material_row.cost_price) - material_row.cost_price
    END;
    unit_price := material_row.cost_price + unit_markup;
    INSERT INTO order_materials (
      expense_id, material_id, material_name, count, price, totalprice,
      unit_cost, total_cost, unit_markup, total_markup, format_id, format_name
    ) VALUES (
      new_order_id,
      NULLIF(line->>'material_id', '')::BIGINT,
      COALESCE(NULLIF(line->>'material_name', ''), 'Material'),
      line_count,
      unit_price,
      unit_price * line_count,
      material_row.cost_price,
      material_row.cost_price * line_count,
      unit_markup,
      unit_markup * line_count,
      NULLIF(line->>'format_id', '')::BIGINT,
      NULLIF(line->>'format_name', '')
    );
  END LOOP;

  RETURN new_order_id;
END;
$$;

CREATE OR REPLACE FUNCTION delete_order_with_restock(order_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
  line RECORD;
  locked_order_id BIGINT;
BEGIN
  SELECT expenses.id
  INTO locked_order_id
  FROM expenses
  WHERE expenses.id = order_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Buyurtma topilmadi';
  END IF;

  FOR line IN
    SELECT material_id, count
    FROM order_materials
    WHERE expense_id = order_id AND material_id IS NOT NULL
    FOR UPDATE
  LOOP
    UPDATE materials
    SET stock_count = stock_count + line.count
    WHERE id = line.material_id;
  END LOOP;

  DELETE FROM expenses WHERE id = order_id;
END;
$$;

CREATE OR REPLACE FUNCTION create_inventory_sale(sale_data JSONB)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  material_row RECORD;
  sale_id_value BIGINT;
  payment_id_value BIGINT;
  material_id_value BIGINT;
  client_id_value BIGINT;
  quantity_value INTEGER;
  quantity_numeric NUMERIC;
  amount_paid_value NUMERIC;
  sale_total_value NUMERIC;
  total_cost_value NUMERIC;
BEGIN
  material_id_value := NULLIF(sale_data->>'material_id', '')::BIGINT;
  client_id_value := NULLIF(sale_data->>'client_id', '')::BIGINT;
  quantity_numeric := COALESCE(NULLIF(sale_data->>'quantity', '')::NUMERIC, 0);
  amount_paid_value := COALESCE(NULLIF(sale_data->>'amount_paid', '')::NUMERIC, 0);

  IF material_id_value IS NULL THEN
    RAISE EXCEPTION 'Materialni tanlang';
  END IF;
  IF quantity_numeric <= 0 OR quantity_numeric <> trunc(quantity_numeric) THEN
    RAISE EXCEPTION 'Sotiladigan miqdor musbat butun son bo‘lishi kerak';
  END IF;
  IF amount_paid_value < 0 THEN
    RAISE EXCEPTION 'Qabul qilingan summa manfiy bo‘lishi mumkin emas';
  END IF;
  IF COALESCE(NULLIF(sale_data->>'payment_type', ''), 'cash')
    NOT IN ('cash', 'card', 'transfer') THEN
    RAISE EXCEPTION 'To‘lov turini to‘g‘ri tanlang';
  END IF;

  SELECT id, name, stock_count, cost_price, sell_price
  INTO material_row
  FROM public.materials
  WHERE id = material_id_value
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Material omborda topilmadi';
  END IF;

  quantity_value := quantity_numeric::INTEGER;
  IF material_row.stock_count < quantity_value THEN
    RAISE EXCEPTION '% materialidan omborda faqat % dona bor',
      material_row.name, material_row.stock_count;
  END IF;

  IF client_id_value IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.clients WHERE id = client_id_value
  ) THEN
    RAISE EXCEPTION 'Tanlangan mijoz topilmadi';
  END IF;

  sale_total_value := material_row.sell_price * quantity_value;
  total_cost_value := material_row.cost_price * quantity_value;
  IF amount_paid_value > sale_total_value THEN
    RAISE EXCEPTION 'Qabul qilingan summa savdo jami summasidan oshmasligi kerak';
  END IF;

  INSERT INTO public.inventory_sales (
    material_id, client_id, material_name, quantity, unit_cost,
    unit_sale_price, total_cost, sale_total, profit, notes
  ) VALUES (
    material_row.id,
    client_id_value,
    material_row.name,
    quantity_value,
    material_row.cost_price,
    material_row.sell_price,
    total_cost_value,
    sale_total_value,
    sale_total_value - total_cost_value,
    NULLIF(btrim(sale_data->>'notes'), '')
  ) RETURNING id INTO sale_id_value;

  UPDATE public.materials
  SET stock_count = stock_count - quantity_value
  WHERE id = material_row.id;

  IF amount_paid_value > 0 THEN
    INSERT INTO public.inventory_sale_payments (
      inventory_sale_id, amount, payment_type, notes
    ) VALUES (
      sale_id_value,
      amount_paid_value,
      COALESCE(NULLIF(sale_data->>'payment_type', ''), 'cash'),
      'Material savdosi uchun to‘lov'
    ) RETURNING id INTO payment_id_value;
  END IF;

  RETURN sale_id_value;
END;
$$;

CREATE OR REPLACE FUNCTION record_inventory_sale_payment(
  sale_id BIGINT,
  amount NUMERIC,
  payment_type TEXT DEFAULT 'cash',
  notes TEXT DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  payment_id_value BIGINT;
  normalized_type TEXT := COALESCE(NULLIF(payment_type, ''), 'cash');
BEGIN
  IF amount IS NULL OR amount <= 0 THEN
    RAISE EXCEPTION 'To‘lov summasi noldan katta bo‘lishi kerak';
  END IF;
  IF normalized_type NOT IN ('cash', 'card', 'transfer') THEN
    RAISE EXCEPTION 'To‘lov turini to‘g‘ri tanlang';
  END IF;

  INSERT INTO public.inventory_sale_payments (
    inventory_sale_id, amount, payment_type, notes
  ) VALUES (
    sale_id, amount, normalized_type, NULLIF(btrim(notes), '')
  ) RETURNING id INTO payment_id_value;

  RETURN payment_id_value;
END;
$$;

